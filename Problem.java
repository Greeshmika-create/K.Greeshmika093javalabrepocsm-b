class Problem
{
	public static void main(String[] args)
	{
		int g=93;
		int k=111;
		System.out.println("g + k = "+(g+k));
		System.out.println("g - k = "+(g-k));
		System.out.println("g * k = "+(g*k));
		System.out.println("g / k = "+(g/k));
		System.out.println("g & k = "+(g&k));
		System.out.println("g | k = "+(g|k));
		System.out.println("g >> k = "+(g>>k));
		System.out.println("g << k = "+(g<<k));
		System.out.println("g == k = "+(g==k));
		System.out.println("g != k = "+(g!=k));
		System.out.println("g > k = "+(g>k));
		System.out.println("g < k = "+(g<k));
		System.out.println("g <= k = "+(g<=k));
		System.out.println("g >= k = "+(g>=k));
		System.out.println("g+1 = "+(g+=1));
		System.out.println("g-1 = "+(g-=1));
		System.out.println("k+2 = "+(k+=2));
		System.out.println("k-2 = "+(k-=2));
	}
}